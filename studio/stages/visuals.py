log = get_logger("visuals")
OWN_LICENCE = "Own work (generated by studio)"
UNSET = object()
MAX_TRIES = 4  # candidates examined per shot before moving on to the next source


def media_hash(path: Path, kind: str) -> int | None:
    """Perceptual hash of a photo or clip, for spotting the same picture twice."""
    return video_hash(path) if kind == "clip" else dhash(path)


def find_valid(prov, keywords: list[str], seen: set, kind: str, hashes: list[int], rejected: list[str],
               avoid: set[str] | None = None, scorer=None, query: str = ""):
    """Next candidate from `prov` that passes the quality gate and is not a near-duplicate of an earlier shot.

    Bad candidates are noted in `rejected` and skipped (the provider already marks them as seen). Assets in
    `avoid` (used by the channel's last videos) are skipped while tries remain; the last try accepts a reuse.
    With a semantic `scorer`, up to three candidates are fetched and the best match for `query` is kept.
    """
    for attempt in range(MAX_TRIES):
        clip = prov.find(keywords, seen)
        if clip is None:
            return None
        if scorer is not None and query:
            extra = [c for c in (prov.find(keywords, seen) for _ in range(2)) if c is not None]
            from studio.story.visuals import best_candidate
            clip = best_candidate(scorer, query, [clip, *extra])
        if avoid and clip.page_url in avoid and attempt < MAX_TRIES - 1:
            rejected.append(f"{clip.path.name}: used in a recent video")
            continue
        problems = check_media(clip.path, kind)
        h = None if problems else media_hash(clip.path, kind)
        if not problems and h is not None and any(similar(h, o) for o in hashes):
            problems = [f"{clip.path.name}: near-duplicate of an earlier shot"]
        if not problems:
            if h is not None:
                hashes.append(h)
            return clip
        rejected.append(problems[0])
        log.info("Rejected %s candidate: %s", kind, problems[0])
    return None


def scene_note(seg: dict, scene: dict, sources: list[dict]) -> str:
    """On-screen note for a scene: always empty. Sources are checked but shown in the description."""
    if scene.get("source_ids"):
        source_line({"source_ids": scene["source_ids"], "title": scene.get("title", "")}, sources)
    elif scene["kind"] == "chart3d" and seg.get("chart_data"):
        source_line(seg["chart_data"], sources)
    return ""


def chart_gaps(segs: list[dict]) -> list[str]:
    """Always empty: charts are rare by design (`quality/visual_mix.py`), so long stretches without one are fine."""
    return []


def run(ctx: Ctx, video_id: int, force: bool = False, stock=UNSET, images=UNSET) -> None:
    """stock / images: providers with find(keywords, exclude); None means not used. Both None: cards only."""
    s = ctx.session
    video = get_video(s, video_id)

    def work() -> None:
        from studio import production
        prod = production.resolve(ctx.settings, video_id)
        folder = ctx.settings.project_dir(video_id)
        total = len(load_package(ctx, video_id)["segments"])
        with progress.tracking(folder, "visuals", total, "segments") as prog, \
                brand.use(prod["palette"], prod.get("theme")):
            _work(prod, prog)

    def _work(prod: dict, prog: progress.Run) -> None:
        nonlocal stock, images
        if stock is UNSET:
            name, stock = make_footage(ctx.settings)
            if stock is None:
                typer.secho(
                    "No stock footage provider configured: using generated cards and charts only. "
                    "To add real footage, set PIXABAY_API_KEY (free, pixabay.com/api/docs/) in .env.",
                    fg=typer.colors.YELLOW)
            else:
                typer.echo(f"Stock footage provider: {name}.")
        if images is UNSET:
            iname, images = make_images(ctx.settings)
            typer.echo(f"Image sources: {iname}." if images else "Image search is off (IMAGE_PROVIDER=none).")
        out = ctx.settings.project_dir(video_id)
        clips_dir, charts_dir = out / "clips", out / "charts"
        clips_dir.mkdir(exist_ok=True)
        (out / "scenes").mkdir(exist_ok=True)
        pkg = load_package(ctx, video_id)
        for note in visual_mix.limit_charts(pkg["segments"]):
            log.info("Visual mix: %s", note)
        limits = rules.edit_limits(ctx.settings.root)
        new_assets: list[Asset] = []  # written in one short transaction after the slow work
        rows = {r.position: r for r in s.query(Segment).filter_by(video_id=video_id)}
        used: set[int] = set()
        used_img: set = set()
        hashes: list[int] = []
        rejected: list[str] = []
        fallbacks = 0
        animated = 0
        blender = render3d.Blender3D(ctx.settings.blender_path)
        scene_counts: dict[str, int] = {}
        from studio.history import cast as cast_mod
        from studio.history import render as cast_render
        planned = {p: scenes.plan_for(g, p, prod) for p, g in enumerate(pkg["segments"], 1)}
        todo3d = {p: min(float(g.get("real_seconds") or g["est_seconds"]), render3d.MAX_SECONDS)
                  for p, g in enumerate(pkg["segments"], 1) if (planned[p] or {}).get("mode") == "3d"}
        budget = SceneBudget(count=len(todo3d), folder=out)
        budget.segments, budget.run = len(pkg["segments"]), prog
        progress.clear_cancel(out)
        if todo3d:
            typer.echo(f"{len(todo3d)} scenes will be rendered in 3D (about {render3d.FPS_3D} frames per second of "
                       f"video). Progress and time left are shown per scene; cancel any time with "
                       f"'cancel {video_id}' or the Cancel button.")
        from studio.story import photo as story_photo
        from studio.story import profile as sprofile
        from studio.story import visuals as story_visuals
        sprof = sprofile.for_channel(ctx.settings.root)
        use_intent = sprofile.enabled(sprof, "visual_intent")
        avoid = story_visuals.recent_assets(ctx.settings.root, 3, video_id) \
            if sprofile.enabled(sprof, "footage_reuse_ledger") else set()
        scorer = story_visuals.make_scorer() if sprofile.enabled(sprof, "semantic_visuals") else None
        cast_on = sprofile.enabled(sprof, "cast_scenes")
        cast_stage = cast_render.Cast(out / "cast") if cast_on else None
        faction0 = 0
        stills = 0
        for pos, seg in enumerate(pkg["segments"], 1):
            left3d = None
            if budget.sec_per_frame and todo3d:
                left3d = (budget.remaining + todo3d.get(pos, 0)) * render3d.FPS_3D * budget.sec_per_frame
            prog.step(pos - 1, f"Segment {pos} of {len(pkg['segments'])}", eta_seconds=left3d,
                      scene=budget.finished, scenes=budget.count)
            vis: dict = {}
            duration = float(seg.get("real_seconds") or seg["est_seconds"])
            bg_seconds, _ = split_segment(duration, bool(seg.get("chart_data")))
            found = []
            drawn = None  # a cast scene (studio/history/render.py) replaces stock footage for this segment
            queries = story_visuals.queries_for(seg) if use_intent else seg["visual_keywords"]
            photo_mode = cast_kind = None
            ask = story_photo.request(seg)
            if ask and images:  # the script asked for a real photo here (and only here)
                try:
                    pic = find_valid(images, [ask["subject"], *queries], used_img, "image", hashes, rejected, avoid)
                    if pic:
                        drawn = photo_scene.render_photo_scene(pic.path, out / "scenes" / f"photo_{pos:03d}.mp4",
                                                               duration, ask["caption"], ask["layout"])
                        photo_mode = ask["layout"]
                        new_assets.append(Asset(video_id=video_id, kind="image", path=str(pic.path),
                                    source=f"{pic.provider}: {pic.author}".strip(), licence=pic.licence,
                                    attribution_url=pic.page_url))
                        scene_counts["photo"] = scene_counts.get("photo", 0) + 1
                except Exception as exc:  # noqa: BLE001 - key rejected, offline, bad file: keep the drawn scene
                    log.warning("Photo scene skipped for segment %d (%s): %s", pos, ask["subject"], exc)
                    drawn = None
                if not drawn:
                    rejected.append(f"segment {pos}: no usable photo for {ask['subject']!r}; drawn scene used")
            if drawn:
                pass
            elif cast_on and (cast_kind := visual_mix.cast_scene_for(seg, cast_mod.SCENE_TYPES)):
                audio = Path(rows[pos].audio_path) if pos in rows and rows[pos].audio_path else None
                drawn = cast_render.render_scene({**seg, "scene": cast_kind}, duration,
                                                 out / "cast" / f"cast_{pos:03d}.mp4", out / "cast",
                                                 audio, faction0, cast_stage)
                scene_counts["cast"] = scene_counts.get("cast", 0) + 1
            query = " ".join([str((seg.get("visual_intent") or {}).get("must_show") or ""), seg.get("narration", "")]) \
                if scorer else ""
            for _ in range(0 if drawn else max(1, shots_needed(bg_seconds, shot_max=shot_max_for(pos, limits)))):
                # alternate video and photo so the picture type changes with every shot; fall back to the other
                order = [("clip", stock, used), ("image", images, used_img)]
                got = False
                for kind, prov, seen in order:  # clips first; a still photo only when no clip is found
                    if kind == "image" and stills >= visual_mix.STOCK_STILL_MAX:
                        continue
                    clip = find_valid(prov, queries, seen, kind, hashes, rejected, avoid, scorer,
                                      query) if prov else None
                    if clip:
                        got = True
                        stills += kind == "image"
                        found.append((kind, clip))
                        new_assets.append(Asset(video_id=video_id, kind=kind, path=str(clip.path),
                                    source=f"{clip.provider}: {clip.author}".strip(), licence=clip.licence,
                                    attribution_url=clip.page_url))
                        break
                if not got:
                    break  # nothing more to find for this segment
            if drawn and photo_mode:
                vis.update(kind="scene", path=str(drawn), paths=[str(drawn)], scene_clip=str(drawn),
                           scene={"kind": "photo", "mode": "photo", "fell_back": False})
            elif drawn:
                vis.update(kind="scene", path=str(drawn), paths=[str(drawn)], scene_clip=str(drawn),
                           scene={"kind": cast_kind, "mode": "cast", "fell_back": False})
                new_assets.append(Asset(video_id=video_id, kind="scene", path=str(drawn), licence=OWN_LICENCE,
                                        source=f"generated cast scene ({cast_kind})"))
            elif found:
                vis.update(kind=found[0][0], path=str(found[0][1].path), paths=[str(c.path) for _, c in found])
            else:
                fallbacks += 1
                log.info("No stock clip for segment %d (%s); using a generated card", pos, seg["visual_keywords"])
                card = text_card(seg.get("chapter") or seg["visual_keywords"][0], "", clips_dir / f"card_{pos:03d}.png",
                                 ctx.settings.assets_dir)
                vis.update(kind="card", path=str(card), paths=[str(card)])
                new_assets.append(Asset(video_id=video_id, kind="card", path=str(card), source="generated card",
                            licence=OWN_LICENCE))
            if seg.get("chart_data"):
                frames = render_chart(seg["chart_data"], pkg["sources"], charts_dir, f"seg_{pos:03d}")
                vis["chart_frames"] = [str(f) for f in frames]
                if os.getenv("STUDIO_NO_CHART_ANIM", "") not in ("1", "true", "yes"):
                    anims = chart_anim.animate(seg["chart_data"], frames, "", charts_dir)
                    animated += len(anims)
                for f in frames:
                    new_assets.append(Asset(video_id=video_id, kind="chart", path=str(f),
                                source=source_line(seg["chart_data"], pkg["sources"]), licence=OWN_LICENCE))
            pl = planned[pos]
            if pl:
                note = scene_note(seg, pl["scene"], pkg["sources"])
                budget.remaining = sum(s for p, s in todo3d.items() if p > pos)
                res = scene_stage.draw(pl, seg, pos, out / "scenes", charts_dir, blender, note, duration, budget,
                                       Path(rows[pos].audio_path) if pos in rows and rows[pos].audio_path else None)
                if pos in todo3d:
                    todo3d.pop(pos)
                    if res["mode"] == "3d":
                        left = ""
                        if budget.sec_per_frame and budget.remaining:
                            left = progress.fmt_duration(budget.remaining * render3d.FPS_3D * budget.sec_per_frame)
                        typer.echo(f"3D scene {budget.finished} of {budget.count} done"
                                   + (f"; about {left} left for the rest." if left else "."))
                scene_counts[res["mode"]] = scene_counts.get(res["mode"], 0) + 1
                vis["scene"] = {"kind": res["kind"], "mode": res["mode"], "fell_back": res["fell_back"]}
                if res["clip"]:
                    vis["scene_clip"] = str(res["clip"])
                    if res["replaces_chart"]:
                        vis.pop("chart_frames", None)
                if res["frames"]:
                    vis["chart_frames"] = [str(f) for f in res["frames"]] + vis.get("chart_frames", [])
                src = res["clip"] or (res["frames"][0] if res["frames"] else None)
                if src:
                    new_assets.append(Asset(video_id=video_id, kind="scene", path=str(src), licence=OWN_LICENCE,
                                source=f"generated {res['mode'].upper()} {res['kind']} scene"))
            seg["visual"] = vis
            if pos in rows:
                rows[pos].clip_path = vis["path"]
        pkg["visual_rejects"] = rejected
        s.query(Asset).filter(Asset.video_id == video_id,
                              Asset.kind.in_(["clip", "image", "card", "chart", "scene"])).delete()
        s.add_all(new_assets)
        s.commit()  # release the write lock before reports and file writes
        story_visuals.record_assets(ctx.settings.root, video_id,
                                    [a.attribution_url for a in new_assets if a.kind in ("clip", "image") and a.attribution_url])  # noqa: E501
        write_package(ctx, video_id, pkg)
        if rejected:
            typer.echo(f"Quality gate rejected {len(rejected)} bad or duplicate candidates (e.g. {rejected[0]}).")
        charts = sum(1 for g in pkg["segments"] if g.get("chart_data"))
        shots = [(a.kind) for a in s.query(Asset).filter(Asset.video_id == video_id, Asset.kind.in_(["clip", "image"]))]
        typer.echo(f"Visuals: {shots.count('clip')} stock clips, {shots.count('image')} photos, "
                   f"{fallbacks} segments on generated cards, "
                   f"{charts} charts.")
        if scene_counts:
            typer.echo("Scenes: " + ", ".join(f"{n} in {m.upper()}" for m, n in sorted(scene_counts.items())) + ".")
        from studio import render_report
        rep = render_report.preflight(ctx.settings, video_id, pkg["segments"])
        rep["scenes"], rep["animated_charts"] = scene_counts, animated
        fell = [p for p, g in enumerate(pkg["segments"], 1) if (g["visual"].get("scene") or {}).get("fell_back")]
        if fell:
            rep["notes"].append(f"Segments {fell} were meant to be 3D but fell back to 2D (see the messages above).")
        rep["verdict"] = "3D" if scene_counts.get("3d", 0) else "2D"
        render_report.save(ctx.settings, video_id, rep)
        for line in render_report.summary(rep):
            typer.secho(line, fg=typer.colors.YELLOW if rep["notes"] else typer.colors.GREEN)
        for w in chart_gaps(pkg["segments"]):
            typer.secho(f"warning: {w}", fg=typer.colors.YELLOW)

    r = run_stage(s, video, "visuals_ready", work, force)
    typer.echo(r.message + (f" Next: build {video_id}" if r.ran else ""))


def visual_paths(seg: dict) -> tuple[list[Path], list[Path]]:
    """(background clips/cards, chart frames) for a segment from script.json."""
    vis = seg.get("visual") or {}
    return [Path(p) for p in vis.get("paths", [])], [Path(p) for p in vis.get("chart_frames", [])]
