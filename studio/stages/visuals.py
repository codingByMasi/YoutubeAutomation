"""`visuals`: stock clip (or fallback card) and chart frames for every segment, with licence records."""

from __future__ import annotations

from pathlib import Path

import typer

from studio.context import Ctx
from studio.models import Asset, Segment
from studio.providers.charts import render_chart, source_line, text_card
from studio.providers.footage import make_footage
from studio.stages.base import get_video, run_stage
from studio.stages.script import CHART_GAP_MAX, load_package, timeline, write_package
from studio.stages.timing import shots_needed, split_segment
from studio.util.logging import get_logger

log = get_logger("visuals")
OWN_LICENCE = "Own work (generated by studio)"
UNSET = object()


def chart_gaps(segs: list[dict]) -> list[str]:
    """Warn where more than CHART_GAP_MAX seconds pass without a chart."""
    warns, last = [], 0.0
    spans = timeline(segs)
    for (start, _), seg in zip(spans, segs):
        if seg.get("chart_data"):
            if start - last > CHART_GAP_MAX:
                warns.append(f"{start - last:.0f}s without a chart before {start / 60:.1f} min")
            last = start
    return warns


def run(ctx: Ctx, video_id: int, force: bool = False, stock=UNSET) -> None:
    """stock: a footage provider with find(keywords, exclude); None means generated cards only."""
    s = ctx.session
    video = get_video(s, video_id)

    def work() -> None:
        nonlocal stock
        if stock is UNSET:
            name, stock = make_footage(ctx.settings)
            if stock is None:
                typer.secho(
                    "No stock footage provider configured: using generated cards and charts only. "
                    "To add real footage, set PIXABAY_API_KEY (free, pixabay.com/api/docs/) in .env.",
                    fg=typer.colors.YELLOW)
            else:
                typer.echo(f"Stock footage provider: {name}.")
        out = ctx.settings.project_dir(video_id)
        clips_dir, charts_dir = out / "clips", out / "charts"
        clips_dir.mkdir(exist_ok=True)
        pkg = load_package(ctx, video_id)
        s.query(Asset).filter(Asset.video_id == video_id, Asset.kind.in_(["clip", "card", "chart"])).delete()
        rows = {r.position: r for r in s.query(Segment).filter_by(video_id=video_id)}
        used: set[int] = set()
        fallbacks = 0
        for pos, seg in enumerate(pkg["segments"], 1):
            vis: dict = {}
            duration = float(seg.get("real_seconds") or seg["est_seconds"])
            bg_seconds, _ = split_segment(duration, bool(seg.get("chart_data")))
            found = []
            for _ in range(max(1, shots_needed(bg_seconds))):
                clip = stock.find(seg["visual_keywords"], used) if stock else None
                if not clip:
                    break
                found.append(clip)
                s.add(Asset(video_id=video_id, kind="clip", path=str(clip.path),
                            source=f"{clip.provider}: {clip.author}".strip(), licence=clip.licence,
                            attribution_url=clip.page_url))
            if found:
                vis.update(kind="clip", path=str(found[0].path), paths=[str(c.path) for c in found])
            else:
                fallbacks += 1
                log.info("No stock clip for segment %d (%s); using a generated card", pos, seg["visual_keywords"])
                card = text_card(seg.get("chapter") or seg["visual_keywords"][0], "", clips_dir / f"card_{pos:03d}.png",
                                 ctx.settings.assets_dir)
                vis.update(kind="card", path=str(card), paths=[str(card)])
                s.add(Asset(video_id=video_id, kind="card", path=str(card), source="generated card",
                            licence=OWN_LICENCE))
            if seg.get("chart_data"):
                frames = render_chart(seg["chart_data"], pkg["sources"], charts_dir, f"seg_{pos:03d}")
                vis["chart_frames"] = [str(f) for f in frames]
                for f in frames:
                    s.add(Asset(video_id=video_id, kind="chart", path=str(f),
                                source=source_line(seg["chart_data"], pkg["sources"]), licence=OWN_LICENCE))
            seg["visual"] = vis
            if pos in rows:
                rows[pos].clip_path = vis["path"]
        write_package(ctx, video_id, pkg)
        charts = sum(1 for g in pkg["segments"] if g.get("chart_data"))
        clips = sum(len(g["visual"]["paths"]) for g in pkg["segments"] if g["visual"]["kind"] == "clip")
        typer.echo(f"Visuals: {clips} stock clips, {fallbacks} segments on generated cards, "
                   f"{charts} charts.")
        for w in chart_gaps(pkg["segments"]):
            typer.secho(f"warning: {w}", fg=typer.colors.YELLOW)

    r = run_stage(s, video, "visuals_ready", work, force)
    typer.echo(r.message + (f" Next: build {video_id}" if r.ran else ""))


def visual_paths(seg: dict) -> tuple[list[Path], list[Path]]:
    """(background clips/cards, chart frames) for a segment from script.json."""
    vis = seg.get("visual") or {}
    return [Path(p) for p in vis.get("paths", [])], [Path(p) for p in vis.get("chart_frames", [])]
