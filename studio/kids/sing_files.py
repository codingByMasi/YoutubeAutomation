"""Write a sing plan as files OpenUtau can open: a MIDI file (with lyric events) and a .ustx project (YAML)."""

from __future__ import annotations

import json
import struct
from pathlib import Path

DEFAULT_PHONEMIZER = "OpenUtau.Plugin.Builtin.ArpasingPlusPhonemizer"


def _vlq(n: int) -> bytes:
    out = [n & 0x7F]
    n >>= 7
    while n:
        out.append((n & 0x7F) | 0x80)
        n >>= 7
    return bytes(reversed(out))


def midi_bytes(plan: dict) -> bytes:
    """A format-0 MIDI file: tempo, then lyric + note-on/off for every note."""
    ppq = plan["ppq"]
    events: list[tuple[int, int, bytes]] = []  # (tick, order, data); order puts note-off before the next note-on
    for n in plan["notes"]:
        start = round(n["start_beat"] * ppq)
        end = start + round(n["beats"] * ppq) - 10  # tiny gap so notes never overlap
        lyric = n["lyric"].encode("utf-8")
        events.append((start, 1, b"\xff\x05" + _vlq(len(lyric)) + lyric))
        events.append((start, 2, bytes([0x90, n["tone"], 90])))
        events.append((end, 0, bytes([0x80, n["tone"], 0])))
    events.sort(key=lambda e: (e[0], e[1]))
    usec = round(60_000_000 / plan["tempo"])
    track = b"\x00\xff\x51\x03" + usec.to_bytes(3, "big")
    last = 0
    for tick, _, data in events:
        track += _vlq(tick - last) + data
        last = tick
    track += b"\x00\xff\x2f\x00"
    return b"MThd" + struct.pack(">IHHH", 6, 0, 1, ppq) + b"MTrk" + struct.pack(">I", len(track)) + track


def _q(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)  # JSON strings are valid YAML scalars


def ustx_text(plan: dict, phonemizer: str = DEFAULT_PHONEMIZER) -> str:
    """A minimal OpenUtau project (YAML). No singer is set: choose the voicebank in OpenUtau after opening."""
    ppq = plan["ppq"]
    lines = [f"name: {_q(plan['title'])}", "comment: generated by YouTube Channel Studio", "ustx_version: 0.6",
             f"resolution: {ppq}", f"bpm: {plan['tempo']}", "beat_per_bar: 4", "beat_unit: 4",
             "tracks:", f"- phonemizer: {_q(phonemizer)}", "  track_name: Vocal",
             "voice_parts:", "- name: Song", "  track_no: 0", "  position: 0", "  notes:"]
    for n in plan["notes"]:
        lines += [f"  - position: {round(n['start_beat'] * ppq)}",
                  f"    duration: {round(n['beats'] * ppq) - 10}",
                  f"    tone: {n['tone']}", f"    lyric: {_q(n['lyric'])}"]
    return "\n".join(lines) + "\n"


def write_all(plan: dict, out_dir: Path) -> dict[str, Path]:
    """Write song.mid, song.ustx, lyrics.txt and sing_plan.json into `out_dir`; return their paths."""
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = {"midi": out_dir / "song.mid", "ustx": out_dir / "song.ustx", "lyrics": out_dir / "lyrics.txt",
             "plan": out_dir / "sing_plan.json"}
    paths["midi"].write_bytes(midi_bytes(plan))
    paths["ustx"].write_text(ustx_text(plan), encoding="utf-8")
    words = [n["lyric"] for n in plan["notes"]]
    paths["lyrics"].write_text(" ".join(words) + "\n", encoding="utf-8")
    paths["plan"].write_text(json.dumps(plan, indent=2), encoding="utf-8")
    return paths
